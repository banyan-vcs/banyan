// T76 — the closing pair (docs/19). CheckBlobsGenerated answers go-enry's
// generated-file heuristic (package-lock.json et al. versus hand-written
// sources); SSHUploadArchive speaks git's upload-archive wire protocol —
// the oracle is the band-1 payload reassembled from the stream and
// compared byte-for-byte with `git archive` of the same tree.
package gitalyrpc

import (
	"bytes"
	"context"
	"io"
	"net"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/banyan-vcs/banyan/integration/support"
	"github.com/banyan-vcs/banyan/internal/gitaly"
	"github.com/banyan-vcs/banyan/internal/gitalypb"
	"github.com/banyan-vcs/banyan/internal/model"
)

func TestT76GitalyClosingPair(t *testing.T) {
	support.NeedGit(t)
	s, meta, objects := support.NewServerPlane(t)
	gs := gitaly.NewServer(meta, objects, model.SHA1, gitaly.Options{Token: "t76"})
	lis, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	go func() { _ = gs.Serve(lis) }()
	t.Cleanup(gs.Stop)
	conn, err := gitaly.Dial(lis.Addr().String(), "t76")
	require.NoError(t, err)
	t.Cleanup(func() { _ = conn.Close() })
	ctx := context.Background()
	as := gitalypb.NewAnalysisServiceClient(conn)
	ss := gitalypb.NewSSHServiceClient(conn)

	src := t.TempDir()
	support.Git(t, src, "init", "-q", "-b", "main", ".")
	support.Write(t, src+"/main.go", "package main\n\nfunc main() {}\n")
	support.Write(t, src+"/package-lock.json", `{
  "name": "demo",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {"": {"name": "demo", "version": "1.0.0"}}
}
`)
	support.Write(t, src+"/app.min.js", "//! minified content generated by build\nvar a=1;function b(){return a}\n")
	support.Git(t, src, "add", "-A")
	support.GitDated(t, src, 1700000000, "commit", "-qm", "mixed sources")
	support.Git(t, src, "push", "-q", s.RepoURL("t76"), "main")
	repo := &gitalypb.Repository{StorageName: "default", RelativePath: "t76"}

	t.Run("check blobs generated", func(t *testing.T) {
		stream, err := as.CheckBlobsGenerated(ctx)
		require.NoError(t, err)
		require.NoError(t, stream.Send(&gitalypb.CheckBlobsGeneratedRequest{
			Repository: repo,
			Blobs: []*gitalypb.CheckBlobsGeneratedRequest_Blob{
				{Revision: []byte("HEAD:package-lock.json"), Path: []byte("package-lock.json")},
				{Revision: []byte("HEAD:main.go"), Path: []byte("main.go")},
			},
		}))
		require.NoError(t, stream.CloseSend())
		var blobs []*gitalypb.CheckBlobsGeneratedResponse_Blob
		for {
			resp, rerr := stream.Recv()
			if rerr != nil {
				break // EOF
			}
			blobs = append(blobs, resp.GetBlobs()...)
		}
		require.Len(t, blobs, 2)
		byRev := map[string]bool{}
		for _, b := range blobs {
			byRev[string(b.GetRevision())] = b.GetGenerated()
		}
		assert.True(t, byRev["HEAD:package-lock.json"], "lockfiles are generated")
		assert.False(t, byRev["HEAD:main.go"], "hand-written source is not")
	})

	t.Run("ssh upload archive matches git archive", func(t *testing.T) {
		wire := &bytes.Buffer{}
		for _, arg := range []string{"--format=tar", "HEAD"} {
			writePktArg(t, wire, "argument "+arg)
		}
		wire.WriteString("0000") // flush

		stream, err := ss.SSHUploadArchive(ctx)
		require.NoError(t, err)
		require.NoError(t, stream.Send(&gitalypb.SSHUploadArchiveRequest{Repository: repo, Stdin: wire.Bytes()}))
		require.NoError(t, stream.CloseSend())
		var stdout []byte
		for {
			resp, rerr := stream.Recv()
			if rerr != nil {
				break // EOF
			}
			stdout = append(stdout, resp.GetStdout()...)
			if resp.GetExitStatus() != nil {
				assert.EqualValues(t, 0, resp.GetExitStatus().GetValue())
			}
		}

		// Wire shape: ACK pkt, flush, then sideband frames to the final flush.
		r := newArchReader(t, stdout)
		ack := r.text()
		assert.Equal(t, "ACK", ack)
		require.True(t, r.flush(), "ACK is flush-terminated")
		var band1 []byte
		for {
			band, payload, flush := r.sideband()
			if flush {
				break
			}
			if band == 1 {
				band1 = append(band1, payload...)
			}
		}
		require.NotEmpty(t, band1)

		gitArchive := support.Git(t, src, "archive", "--format=tar", "HEAD")
		assert.True(t, bytes.Equal([]byte(gitArchive), band1),
			"upload-archive payload must equal git archive byte for byte (got %d vs %d bytes)",
			len(band1), len(gitArchive))
	})

	t.Run("bad arguments answer NACK", func(t *testing.T) {
		wire := &bytes.Buffer{}
		writePktArg(t, wire, "argument --format=7z")
		writePktArg(t, wire, "argument HEAD")
		wire.WriteString("0000")
		stream, err := ss.SSHUploadArchive(ctx)
		require.NoError(t, err)
		require.NoError(t, stream.Send(&gitalypb.SSHUploadArchiveRequest{Repository: repo, Stdin: wire.Bytes()}))
		require.NoError(t, stream.CloseSend())
		var stdout []byte
		var exit int32
		for {
			resp, rerr := stream.Recv()
			if rerr != nil {
				break
			}
			stdout = append(stdout, resp.GetStdout()...)
			if resp.GetExitStatus() != nil {
				exit = resp.GetExitStatus().GetValue()
			}
		}
		assert.EqualValues(t, 1, exit)
		assert.Contains(t, string(stdout), "NACK", "argument errors use the NACK form")
	})
}

// writePktArg renders one pkt-line of the upload-archive request.
func writePktArg(t *testing.T, w *bytes.Buffer, line string) {
	t.Helper()
	_, err := w.WriteString(fmt4(len(line)+5) + line + "\n")
	require.NoError(t, err)
}

func fmt4(n int) string {
	const hex = "0123456789abcdef"
	return string([]byte{hex[n>>12&0xf], hex[n>>8&0xf], hex[n>>4&0xf], hex[n&0xf]})
}

// archReader walks the upload-archive response stream.
type archReader struct {
	t  *testing.T
	r  *bytes.Reader
	b1 [4]byte
}

func newArchReader(t *testing.T, data []byte) *archReader {
	return &archReader{t: t, r: bytes.NewReader(data)}
}

func (p *archReader) readPayload() (int, []byte) {
	n, err := io.ReadFull(p.r, p.b1[:])
	if err != nil {
		p.t.Fatal("short pkt header")
	}
	_ = n
	var length int
	if _, err := fmtSscanHex(string(p.b1[:]), &length); err != nil {
		p.t.Fatalf("bad pkt header %q", p.b1)
	}
	if length == 0 {
		return 0, nil // flush
	}
	buf := make([]byte, length-4)
	if _, err := io.ReadFull(p.r, buf); err != nil {
		p.t.Fatal("short pkt body")
	}
	return length, buf
}

func (p *archReader) text() string {
	_, payload := p.readPayload()
	return strings.TrimRight(string(payload), "\n")
}

func (p *archReader) flush() bool {
	length, _ := p.readPayload()
	return length == 0
}

func (p *archReader) sideband() (byte, []byte, bool) {
	length, payload := p.readPayload()
	if length == 0 {
		return 0, nil, true
	}
	return payload[0], payload[1:], false
}

func fmtSscanHex(s string, out *int) (int, error) {
	n := 0
	for _, c := range s {
		n = n * 16
		switch {
		case c >= '0' && c <= '9':
			n += int(c - '0')
		case c >= 'a' && c <= 'f':
			n += int(c-'a') + 10
		default:
			return 0, io.ErrUnexpectedEOF
		}
	}
	*out = n
	return 1, nil
}
